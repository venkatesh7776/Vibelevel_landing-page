function BlockView({ b }: { b: Block }) {
  if ("p" in b) return <p className="font-body text-[16px] leading-[1.7] text-black/65">{b.p}</p>;
  if ("caps" in b) return <p className="font-body text-[14px] leading-[1.7] font-medium text-black/70">{b.caps}</p>;
  if ("list" in b)
    return (
      <ul className="space-y-2.5">
        {b.list.map((x, i) => (
          <li key={i} className={`flex gap-3 font-body leading-[1.6] text-black/65 ${b.mark === "warn" || b.mark === "arrow" ? "text-[14.5px]" : "text-[16px]"}`}>
            <span aria-hidden="true" className="w-4 shrink-0 text-center">
              {MARKS[b.mark]}
            </span>
            <span>{x}</span>
          </li>
        ))}
      </ul>
    );
  return (
    <dl className="grid gap-3 sm:grid-cols-2">
      {b.items.map((it) => (
        <div key={it.t} className="rounded-[14px] bg-[#f8f8f7] p-4">
          <dt className="font-display text-[15px] font-semibold text-ink-900">{it.t}</dt>
          <dd className="mt-1 font-body text-[15px] leading-[1.6] text-black/60">{it.d}</dd>
        </div>
      ))}
    </dl>
  );
}

